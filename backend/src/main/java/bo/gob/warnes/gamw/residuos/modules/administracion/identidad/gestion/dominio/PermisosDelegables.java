/** Catálogo técnico ya implementado; nunca incluye facultades administrativas delegables por HTTP. */
public final class PermisosDelegables {
    private PermisosDelegables() { }
    public static final Set<String> MUNICIPALES=Set.of("TRAYECTORIA_JORNADA_CONSULTAR","MONITOREO_JORNADA_CONSULTAR",
        "REFERENCIA_ESPACIAL_CONSULTAR","REFERENCIA_ESPACIAL_GESTIONAR","GPS_INTEGRIDAD_REVISAR","GPS_COINCIDENCIAS_REVISAR",
        "GPS_DESVIOS_REVISAR","INSPECCION_REGISTRAR","FISCALIZACION_CONSULTAR","FISCALIZACION_EMITIR",
        "CORRECTIVA_CONSULTAR","CORRECTIVA_SOLICITAR","CORRECTIVA_VERIFICAR","RECLAMO_CONSULTAR","RECLAMO_REGISTRAR","RECLAMO_REVISAR",
        "PUNTO_CRITICO_CONSULTAR","PUNTO_CRITICO_REGISTRAR","PUNTO_CRITICO_VALIDAR","EMPRESAS_CONSULTAR","EMPRESAS_GESTIONAR",
        "PERIODOS_CONSULTAR","PERIODOS_GESTIONAR","PERSONAS_CONSULTAR","PERSONAS_GESTIONAR","VEHICULOS_CONSULTAR","VEHICULOS_GESTIONAR",
        "RUTAS_CONSULTAR","RUTAS_GESTIONAR","JORNADAS_CONSULTAR","JORNADAS_PROGRAMAR","JORNADAS_ASIGNAR");
    public static final Set<String> OPERADOR=Set.of("CORRECTIVA_CONSULTAR","CORRECTIVA_RESPONDER","JORNADA_REPROGRAMAR","PLANIFICACION_CONSULTAR","JORNADA_PROGRAMAR","JORNADA_ASIGNAR");
    public static boolean admite(String permiso,boolean porPeriodo) { return permiso!=null && (porPeriodo?OPERADOR:MUNICIPALES).contains(permiso); }
}
